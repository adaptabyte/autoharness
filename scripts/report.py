#!/usr/bin/env python3
"""Writes docs/PROOF.md and the home page's table from the raw run logs, so no number here is typed in.
  docs/uiteam.jsonl     compiled interfaces, including every failure and every teaching dollar
  docs/paperwork.jsonl  the reading team, including every failed round"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = [json.loads(x) for x in (ROOT / "docs" / "uiteam.jsonl").read_text().splitlines()]
PAPER = [json.loads(x) for x in (ROOT / "docs" / "paperwork.jsonl").read_text().splitlines()]
NAMES = {("portal", "save_request"): "A made-up insurer's portal: fill and save a five-step request", ("openemr", "read_dob"): "OpenEMR: find a patient, read their birth date", ("openemr", "set_phone"): "OpenEMR: change a patient's phone number",
         ("openemr-chart", "read_chart"): "OpenEMR: read a whole chart", ("backoffice", "ship_order"): "Django admin: mark an order shipped", ("backoffice", "read_order"): "Django admin: read an order", ("calculator", "calculate"): "GNOME Calculator, a native desktop app"}
OLD = {("openemr", "read_dob"): "Glimmer + generated program: 0 of 1", ("openemr", "set_phone"): "Glimmer + generated program: 0 of 1", ("openemr-chart", "read_chart"): "Glimmer + written guide: 0 of 6", ("portal", "save_request"): "Generated programs: 0 of 2"}


def med(rows, key):
    return statistics.median(r[key] for r in rows) if rows else None


def ui_rows() -> list[dict]:
    out = []
    labels = {}
    for r in UI:
        if r.get("run", "").startswith("proof"):
            labels.setdefault((r["app"], r["job"]), {}).setdefault(r["run"], []).append(r)
    for key, name in NAMES.items():
        runs = labels.get(key) or {}
        spark = [r for r in UI if r.get("run") == "spark" and (r["app"].replace("openemr", "openemr-chart") if r["job"] == "read_chart" else r["app"], r["job"]) == key]
        final = runs.get("final") or runs.get("proof3") or runs.get("proof2") or runs.get("proof") or []
        out.append(dict(key=key, name=name, attempts={k: f"{sum(x['ok'] for x in v)}/{len(v)}" for k, v in runs.items()}, passes=sum(r["ok"] for r in final), runs=len(final), wrong=sum(bool(r["wrong_saved"]) for r in final), seconds=med(final, "seconds"), questions=med(final, "questions"),
                        spark_pass=sum(r["ok"] for r in spark), spark_runs=len(spark), spark_seconds=med(spark, "seconds"), spark_usd=med(spark, "usd"), spark_bytes=med(spark, "bytes_sent"), old=OLD.get(key, "")))
    return out


def teaching() -> dict:
    out: dict = {}
    for r in UI:
        if r.get("run") == "cost":
            out.setdefault(r["app"], {"explore": 0.0, "compile": 0.0, "repair": 0.0})[r["kind"]] += r["usd"]
    return out


def paper_summary(run: str, mode: str) -> dict | None:
    rows = [r for r in PAPER if r["run"] == run and r["mode"] == mode]
    if not rows:
        return None
    n = lambda v: sum(r["verdict"] == v for r in rows)
    clean = [r for r in rows if r["defect"] == "clean"]
    return dict(packets=len(rows), wrong=n("WRONG_SAVED"), caught=n("caught"), defects=len(rows) - len(clean), cleared=n("cleared_right"), clean=len(clean), seconds=round(med(rows, "seconds"), 1))


def swarm_lines() -> list[str]:
    lines = ["| At once | Finished and verified | Wrong saved | Time for all | Jobs an hour |", "|---|---|---|---|---|"]
    proof = [r for r in UI if r.get("run") == "proof" and r["app"] == "portal"]
    if proof:
        lines.append(f"| 1 | {sum(r['ok'] for r in proof)}/{len(proof)} | {sum(bool(r['wrong_saved']) for r in proof)} | {round(sum(r['seconds'] for r in proof))} s in a row | {round(3600 / med(proof, 'seconds'))} |")
    for n in (4, 8):
        rows = [r for r in UI if r.get("run") == "swarm-summary" and r["at_once"] == n][-1:]
        for r in rows:
            lines.append(f"| {n} | {r['passes']}/{n} | {r['wrong']} | {round(r['wall_s'])} s | {round(r['passes'] / r['wall_s'] * 3600)} |")
    return lines


def money(x) -> str:
    return "—" if x is None else f"${x:.3f}"


def secs(x) -> str:
    return "—" if x is None else f"{round(x)} s"


def main() -> None:
    rows = ui_rows()
    teach = teaching()
    lines = ["# Proof", "", "Generated by `scripts/report.py` from `docs/uiteam.jsonl` and `docs/paperwork.jsonl`. Nothing is typed in, and every failed round stays in those logs.", "", "## Any interface, compiled for a small model", "",
             "Results are checked against each app's own data: OpenEMR's saved record through a separate login, the portal's and Django's own stores, and arithmetic for the calculator. A run that stops and asks for help counts as a failure, but not as a wrong result. Bars were committed to git before the first run (`scripts/uiteam/run.py`). Samples are small.", "",
             "| Job | Glimmer + compiled plan | Wrong saved | Median | Cloud at run time | Muse Spark doing it live | Before this |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        if not r["runs"] and not r["spark_runs"]:
            continue
        spark = f"{r['spark_pass']}/{r['spark_runs']}, {secs(r['spark_seconds'])}, {money(r['spark_usd'])}" if r["spark_runs"] else "—"
        lines.append(f"| {r['name']} | **{r['passes']}/{r['runs']}** | {r['wrong']} | {secs(r['seconds'])} | $0 | {spark} | {r['old']} |")
    lines += ["", "Every proof round, including the ones that missed the bar:", ""]
    for r in rows:
        if r["attempts"]:
            lines.append(f"- {r['name']}: " + ", ".join(f"{k} {v}" for k, v in r["attempts"].items()))
    lines += ["", "## What teaching cost, once", "", "| Interface | Spark exploring | Wonder compiling | Wonder repairing | Total |", "|---|---|---|---|---|"]
    for app, c in teach.items():
        lines.append(f"| {app} | {money(c['explore'])} | {money(c['compile'])} | {money(c['repair'])} | {money(sum(c.values()))} |")
    lines += ["", "## Paperwork, the read-only case", "", "Made-up full-page packets: typed scans, handwriting-style fills, faxes and phone photos, with planted errors. Not real faxes or real handwriting. The bar is in `scripts/paperwork/evaluate.py`: no wrong saved, at least 90% of planted errors caught, at least 60% of clean packets cleared, median under 30 s.", "",
              "| Round | Readers | Wrong saved | Errors caught | Clean cleared | Median |", "|---|---|---|---|---|---|"]
    labels = [("hard30-v1", "team", "First run, tuning set"), ("hard30-v1", "one", "First run, tuning set"), ("hard30-v2-tuning", "team", "No reasoning step, tuning set"), ("hard30-v3b-tuning", "team", "Scan first + second view, tuning set"), ("hard30-final-one", "one", "Same code, tuning set"), ("fresh30-final", "team", "**Unseen set**"), ("fresh30-final", "one", "**Unseen set**"), ("fresh30-fast", "team", "**Second unseen set**, after a speed fix"), ("fresh30-last", "team", "**Third unseen set**, final code"), ("fresh30-last", "one", "**Third unseen set**, final code")]
    for run, mode, name in labels:
        s = paper_summary(run, mode)
        if s:
            lines.append(f"| {name} | {'Team' if mode == 'team' else 'One per page'} | {s['wrong']} | {s['caught']}/{s['defects']} | {s['cleared']}/{s['clean']} | {s['seconds']} s |")
    designed = {}
    for r in PAPER:
        if r.get("mode") == "designed":
            designed.setdefault(r["run"], []).append(r)
    if designed:
        lines += ["", "Teams designed by Muse Wonder from one example, on paperwork it hadn't seen:", "", "| Paperwork | Wrong saved | Defects sent to a person | Clean cleared | Median |", "|---|---|---|---|---|"]
        for run, rr in designed.items():
            n = lambda v: sum(x["verdict"] == v for x in rr)
            bad = n("WRONG_SAVED") + n("cleared_but_value_not_found")
            dfx = [x for x in rr if x["defect"] != "clean"]
            lines.append(f"| {run} | {bad} | {n('caught')}/{len(dfx)} | {n('cleared_right')}/{len(rr) - len(dfx)} | {round(med(rr, 'seconds'), 1)} s |")
    (ROOT / "docs" / "PROOF.md").write_text("\n".join(lines) + "\n")
    readme = ROOT / "README.md"
    start, end = "<!-- proof -->", "<!-- /proof -->"
    text = readme.read_text()
    if start in text:
        short = ["| Job | Glimmer + compiled plan | Median time | Cloud per run | Muse Spark, a screenshot every step |", "|---|---|---|---|---|"]
        for r in rows:
            if r["runs"]:
                spark = f"{r['spark_pass']}/{r['spark_runs']}, {secs(r['spark_seconds'])}, {money(r['spark_usd'])}" if r["spark_runs"] else "—"
                short.append(f"| {r['name']} | **{r['passes']}/{r['runs']}** | {secs(r['seconds'])} | $0 | {spark} |")
        text = text[:text.index(start) + len(start)] + "\n" + "\n".join(short) + "\n" + text[text.index(end):]
        a, b = "<!-- swarm -->", "<!-- /swarm -->"
        text = text[:text.index(a) + len(a)] + "\n" + "\n".join(swarm_lines()) + "\n" + text[text.index(b):]
        readme.write_text(text)
    table = [[r["name"], f"{r['passes']}/{r['runs']}", secs(r["seconds"]), "$0", f"{r['spark_pass']}/{r['spark_runs']}, {secs(r['spark_seconds'])}, {money(r['spark_usd'])}" if r["spark_runs"] else "—"] for r in rows if r["runs"]]
    (ROOT / "docs" / "paperwork-final.json").write_text(json.dumps({"title": "Measured, on inputs it hadn't seen", "columns": ["Job", "Glimmer + plan", "Median", "Cloud per run", "Spark doing it live"], "rows": table, "highlight": None, "note": "Checked against each app's own data. Small samples. Every failed round is in docs/PROOF.md."}, indent=1))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
